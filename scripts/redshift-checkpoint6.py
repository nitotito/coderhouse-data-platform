"""Redshift Data API runner. Default is dry-run; --execute requires cost approval.

Uses AWS CLI temporary credentials, never passwords or embedded credentials.
Python 3.11+; no boto3 dependency. All SQL/evidence use repository-relative paths.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / 'sql' / 'redshift'
EVIDENCE = ROOT / 'docs' / 'evidence' / 'checkpoint-6'
PARTS = sorted(SQL.glob('[0-9][0-9]_*.sql'))


def statements(source: str) -> list[str]:
    # Controlled repository SQL has no block comments or semicolons inside strings.
    # Strip full-line comments, preserving inline literals containing "--".
    source = '\n'.join(line for line in source.splitlines()
                       if not line.lstrip().startswith('--'))
    return [s.strip() for s in source.split(';') if s.strip()]


def consolidate() -> Path:
    target = SQL / 'checkpoint_6_complete.sql'
    target.write_text('-- Generated by scripts/redshift-checkpoint6.py; edit numbered sources.\n'
                      '-- Execute ONCE as deployment owner in database analytics.\n'
                      '-- Re-runs: do not recreate existing MV or role; no implicit DROP.\n\n'
                      + '\n\n'.join('-- SOURCE: ' + p.name + '\n' + p.read_text(encoding='utf-8')
                                      for p in PARTS), encoding='utf-8')
    return target


class Runner:
    def __init__(self, args):
        self.args = args
        EVIDENCE.mkdir(parents=True, exist_ok=True)
        self.counter = 0

    def save(self, name, value):
        (EVIDENCE / name).write_text(json.dumps(value, indent=2, ensure_ascii=False)
                                     + '\n', encoding='utf-8')

    def aws(self, *command):
        result = subprocess.run(['aws', *command, '--profile', self.args.profile,
                                 '--region', self.args.region, '--output', 'json',
                                 '--no-cli-pager'], capture_output=True, text=True,
                                encoding='utf-8', timeout=90)
        if result.returncode:
            raise RuntimeError(result.stderr.strip())
        return json.loads(result.stdout) if result.stdout.strip() else {}

    def query(self, sql, label):
        self.counter += 1
        prefix = f'{self.counter:03d}-{label}'
        response = self.aws('redshift-data', 'execute-statement',
                            '--workgroup-name', self.args.workgroup,
                            '--database', 'analytics', '--sql', sql)
        query_id = response['Id']
        deadline = time.monotonic() + 180
        while time.monotonic() < deadline:
            status = self.aws('redshift-data', 'describe-statement', '--id', query_id)
            if status['Status'] in ('FINISHED', 'FAILED', 'ABORTED'):
                self.save(prefix + '-execution.json', status)
                if status['Status'] != 'FINISHED':
                    raise RuntimeError(f'{label}: {status.get("Error", status["Status"])}')
                if not status.get('HasResultSet'):
                    return []
                # Paginate all results, preserving numeric decimals returned as strings.
                rows = []
                token = None
                while True:
                    command = ['redshift-data', 'get-statement-result', '--id', query_id]
                    if token:
                        command += ['--next-token', token]
                    page = self.aws(*command)
                    names = [c['name'] for c in page['ColumnMetadata']]
                    for record in page['Records']:
                        rows.append(dict(zip(names, [None if v.get('isNull') else
                                                      next(iter(v.values())) for v in record])))
                    token = page.get('NextToken')
                    if not token:
                        break
                self.save(prefix + '-results.json', rows)
                return rows
            time.sleep(3)
        self.aws('redshift-data', 'cancel-statement', '--id', query_id)
        raise TimeoutError(f'{label}: cancelled statement {query_id} after 180s')

    def setup(self):
        for part in PARTS:
            if int(part.name[:2]) > 5:
                continue
            for index, sql in enumerate(statements(part.read_text(encoding='utf-8'))):
                self.query(sql, f'{part.stem}-{index+1}')

    def smoke(self):
        from decimal import Decimal
        run_id = 'pe6_' + dt.datetime.now(dt.timezone.utc).strftime('%Y%m%d_%H%M%S')
        now = dt.datetime.now(dt.timezone.utc).replace(second=0, microsecond=0)
        historic = dt.datetime(2026, 11, 4, 11, 33, tzinfo=dt.timezone.utc)
        methods = ['card_' + run_id, 'card_pe5_20261104_113142']
        # Existing Iceberg snapshot is reused read-only. Historical event time is
        # intentional; arrival in Kinesis is new. Flink remains READY to avoid replay.
        before = self.query("SELECT transaction_count,total_amount FROM lakehouse.transaction_aggregates "
                            "WHERE payment_method='card_pe5_20261104_113142' "
                            "AND window_start=TIMESTAMP '2026-11-04 11:33:00'", 'historical-baseline')
        if len(before) != 1 or int(before[0]['transaction_count']) != 2 or Decimal(str(before[0]['total_amount'])) != Decimal('30.30'):
            raise AssertionError('Historical fixture differs; inspect before publishing records')
        flink = self.aws('kinesisanalyticsv2', 'describe-application', '--application-name',
                         'coderhouse-dev-transactions-flink')['ApplicationDetail']['ApplicationStatus']
        if flink != 'READY':
            raise RuntimeError('Flink must remain READY for the historical read-only reconciliation test')
        existing = self.query("SELECT COUNT(*) AS records FROM analytics.transactions_typed "
                              "WHERE payment_method='card_pe5_20261104_113142'", 'replay-guard')
        if int(existing[0]['records']) != 0:
            raise RuntimeError('Historical dimension already exists in raw MV. Do not replay again; inspect evidence or choose a new historical fixture.')
        events = []
        for n, (method, minute) in enumerate(zip(methods, [now, historic])):
            for index, (amount, status) in enumerate([(10.10, 'APPROVED'), (20.20, 'approved'), (999, 'rejected')]):
                events.append(dict(transaction_id=f'{run_id}-{n}-{index}', amount=amount,
                                   status=status, payment_method=method,
                                   timestamp=(minute + dt.timedelta(seconds=index+1)).isoformat()))
        events += [dict(transaction_id=run_id+'-bad-amount', amount='invalid', status='approved',
                        payment_method=methods[0], timestamp=now.isoformat()),
                   dict(transaction_id=run_id+'-no-time', amount=1, status='approved', payment_method=methods[0])]
        import base64
        sent_at = dt.datetime.now(dt.timezone.utc)
        receipts = []
        for event in events + ['{invalid-json']:
            body = event if isinstance(event, str) else json.dumps(event)
            receipts.append(self.aws('kinesis', 'put-record', '--stream-name', 'dev-transactions-stream',
                                     '--partition-key', run_id, '--data',
                                     base64.b64encode(body.encode()).decode()))
        self.save(run_id+'-events.json', {'events': events, 'invalid_json': '{invalid-json', 'receipts': receipts})
        deadline = time.monotonic() + 180
        rows = []
        while time.monotonic() < deadline:
            self.query('REFRESH MATERIALIZED VIEW streaming.transactions_raw', 'refresh')
            rows = self.query("SELECT * FROM analytics.transactions_typed WHERE transaction_id LIKE '" + run_id + "%'", 'typed')
            if len(rows) >= 8:
                break
            time.sleep(15)
        if len(rows) != 8:
            raise AssertionError(f'Expected 8 JSON records, got {len(rows)}')
        if sum(r['validation_error'] is not None for r in rows) != 2:
            raise AssertionError('Expected invalid amount and missing timestamp diagnostics')
        metrics = self.query("SELECT * FROM analytics.transactions_per_minute WHERE payment_method='"+methods[0]+"'", 'metrics')
        if len(metrics) != 1:
            raise AssertionError('Expected exactly one current-minute metric row')
        metric = metrics[0]
        for field, expected in [('transaction_count', 3), ('approved_count', 2), ('rejected_count', 1)]:
            if int(metric[field]) != expected:
                raise AssertionError(f'{field}: {metric[field]} != {expected}')
        if Decimal(str(metric['total_amount'])) != Decimal('1029.30') or Decimal(str(metric['approved_amount'])) != Decimal('30.30'):
            raise AssertionError('Incorrect business totals')
        comparison = self.query("SELECT * FROM analytics.recent_vs_iceberg WHERE payment_method='"+methods[1]+"'", 'iceberg-join')
        if len(comparison) != 1 or int(comparison[0]['recent_approved_count']) != 2 or Decimal(str(comparison[0]['amount_difference'])) != 0 or int(comparison[0]['count_difference']) != 0:
            raise AssertionError('Expected a single reconciled historical join row')
        invalid = self.query("SELECT COUNT(*) AS records FROM streaming.transactions_raw WHERE partition_key='"+run_id+"' AND NOT valid_json", 'invalid-json')
        if int(invalid[0]['records']) != 1:
            raise AssertionError('Invalid JSON was not retained')
        for part in PARTS:
            if part.name.startswith('07_'):
                for index, sql in enumerate(statements(part.read_text(encoding='utf-8'))):
                    self.query(sql, f'monitor-{index+1}')
        self.save('test-summary.json', {
            'status': 'PASSED', 'run_id': run_id, 'metrics': metrics, 'join': comparison,
            'observation_upper_bound_seconds': (dt.datetime.now(dt.timezone.utc)-sent_at).total_seconds(),
            'note': 'New Kinesis arrivals with both current and historical event times; existing Iceberg fixture read-only. Flink not started.',
            'automatic_refresh_tested': False,
        })


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--execute', action='store_true')
    parser.add_argument('--setup', action='store_true')
    parser.add_argument('--smoke', action='store_true')
    parser.add_argument('--profile', default='coderhouse-dev')
    parser.add_argument('--region', default='us-east-1')
    parser.add_argument('--workgroup', default='coderhouse-dev-analytics')
    args = parser.parse_args()
    print(consolidate().relative_to(ROOT))
    if not args.execute:
        print('Dry run: SQL consolidated. No AWS API calls. --execute only after cost approval.')
        return
    runner = Runner(args)
    try:
        if args.setup:
            runner.setup()
        if args.smoke:
            runner.smoke()
    except Exception as error:
        runner.save('last-failure.json', {'status': 'FAILED', 'error': str(error)})
        raise


if __name__ == '__main__':
    main()
